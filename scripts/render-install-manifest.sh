#!/usr/bin/env bash
# SPDX-License-Identifier: AGPL-3.0-only
# Renders the agent chart (deploy/helm/watchlog-agent) into the manifest Cloud serves at
# /install.yaml?code=wl_ic_… (ADR-176): backend/assets/install-manifest.yaml, committed and
# checked in CI against a fresh render. The chart stays the one source; the backend only
# fills the placeholders per request:
#   - WATCHLOG_INSTALL_ENDPOINT, the ingest address (quoted by the chart);
#   - the token, base64 of WATCHLOG_INSTALL_TOKEN in the token Secret;
#   - WATCHLOG_INSTALL_REGISTRY and WATCHLOG_INSTALL_TAG, the agent images;
#   - WATCHLOG_PODMAP_CA_CRT, _TLS_CRT and _TLS_KEY: the chart generates the pod map's CA and
#     certificate at render time (genCA), which would give every install the same private
#     key, so they are cut out here and the backend makes a new pair for each manifest.
# The namespace is created with the PodSecurity label the helm command applies (ADR-070).
# Needs helm. Run from anywhere: scripts/render-install-manifest.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/backend/assets/install-manifest.yaml"
TOKEN_B64="$(printf '%s' WATCHLOG_INSTALL_TOKEN | base64)"

rendered="$(helm template watchlog-agent "$ROOT/deploy/helm/watchlog-agent" \
  --namespace watchlog \
  --set watchlog.endpoint=WATCHLOG_INSTALL_ENDPOINT \
  --set watchlog.clusterToken=WATCHLOG_INSTALL_TOKEN \
  --set image.registry=WATCHLOG_INSTALL_REGISTRY \
  --set image.tag=WATCHLOG_INSTALL_TAG)"

grep -q "token: $TOKEN_B64\$" <<<"$rendered" || {
  echo "render-install-manifest: the token Secret's shape changed; update this script and backend/src/modules/onboarding/manifest.ts" >&2
  exit 1
}

{
  echo '# SPDX-License-Identifier: AGPL-3.0-only'
  echo '# Generated by scripts/render-install-manifest.sh from deploy/helm/watchlog-agent: do not edit.'
  echo '# The backend fills the WATCHLOG_* placeholders for each install code (ADR-176).'
  echo '---'
  echo 'apiVersion: v1'
  echo 'kind: Namespace'
  echo 'metadata:'
  echo '  name: watchlog'
  echo '  labels:'
  echo '    pod-security.kubernetes.io/enforce: privileged'
  # The pod map's generated CA and certificate become placeholders (see above), and every
  # namespaced object names its namespace: `helm template` leaves that to `helm install`,
  # and `kubectl apply -f` would put them in the current context's namespace.
  sed -E \
    -e 's/^(  ca\.crt: ).*/\1WATCHLOG_PODMAP_CA_CRT/' \
    -e 's/^(  tls\.crt: ).*/\1WATCHLOG_PODMAP_TLS_CRT/' \
    -e 's/^(  tls\.key: ).*/\1WATCHLOG_PODMAP_TLS_KEY/' <<<"$rendered" |
    awk '
      /^---/ { kind = "" }
      /^kind: / { kind = $2 }
      { print }
      /^metadata:$/ && kind !~ /^(Namespace|ClusterRole|ClusterRoleBinding)$/ { print "  namespace: watchlog" }
    '
} >"$OUT"
echo "wrote ${OUT#"$ROOT"/}"
