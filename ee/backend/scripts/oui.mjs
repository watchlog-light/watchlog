// Builds the MAC vendor table (ADR-233) from the IEEE MA-L registry's public CSV
// (https://standards-oui.ieee.org/oui/oui.csv): every 24-bit prefix and its organisation's
// name, shortened ("Cisco Systems, Inc" → "Cisco Systems"), written compactly to
// src/network/oui-data.ts. Not Wireshark's `manuf` (GPL). Run when the registry should be
// refreshed:  node ee/backend/scripts/oui.mjs path/to/oui.csv
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const csv = process.argv[2];
if (!csv) {
  console.error('usage: oui.mjs oui.csv');
  process.exit(2);
}

/** RFC 4180 rows. */
function* rows(text) {
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') {
      row.push(field);
      field = '';
    } else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field);
      field = '';
      yield row;
      row = [];
    } else field += c;
  }
  if (field || row.length) yield [...row, field];
}

const SUFFIX =
  /[\s,.]*(incorporated|inc|corporation|corp|co|company|ltd|limited|llc|l\.l\.c|gmbh|ag|s\.?a|s\.?p\.?a|b\.?v|oy|ab|as|a\/s|plc|pty|pte|kg|sas|s\.r\.l|srl|nv|kk|k\.k)\.?$/i;

function short(name) {
  let s = name.replace(/\s+/g, ' ').trim();
  for (let i = 0; i < 4; i++) {
    const t = s.replace(SUFFIX, '').trim();
    if (t === s || t.length < 2) break;
    s = t;
  }
  return s.replace(/[,.\s]+$/, '').slice(0, 48);
}

const entries = new Map();
for (const r of rows(readFileSync(csv, 'utf8'))) {
  if (r[0] !== 'MA-L' || !/^[0-9A-F]{6}$/.test(r[1] ?? '')) continue;
  const name = short(r[2] ?? '');
  if (name && name.toLowerCase() !== 'private') entries.set(r[1].toLowerCase(), name);
}
const vendors = [...new Set(entries.values())].sort();
const index = new Map(vendors.map((v, i) => [v, i]));
const prefixes = [...entries.keys()].sort();
const packed = prefixes
  .map((p) => p + index.get(entries.get(p)).toString(36).padStart(3, '0'))
  .join('');
const out = fileURLToPath(new URL('../src/network/oui-data.ts', import.meta.url));
writeFileSync(
  out,
  `// SPDX-License-Identifier: LicenseRef-WatchLog-Enterprise
// Generated by ee/backend/scripts/oui.mjs from the IEEE MA-L registry (${prefixes.length} prefixes,
// ${vendors.length} organisations). Do not edit.
/** Organisation names, one per line, by index. */
export const VENDORS = ${JSON.stringify(vendors.join('\n'))};
/** Sorted: 6 hex digits of the prefix, then the vendor's index in base 36 (3 digits). */
export const PREFIXES = ${JSON.stringify(packed)};
`,
);
console.log(`${prefixes.length} prefixes, ${vendors.length} vendors → ${out}`);
