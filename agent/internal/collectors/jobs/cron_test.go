func TestCrontabsAreParsedAndNamedWithoutSecrets(t *testing.T) {
	es := ParseCrontabs(testFS())
	var got []string
	for _, e := range es {
		got = append(got, e.Name+" | "+e.Schedule.Spec+" | "+e.Source)
	}
	expect := []string{
		"cron.hourly | 17 * * * * | /etc/crontab",
		"cron.daily | 25 6 * * * | /etc/crontab",
		"pg_dump | */5 * * * * | /etc/cron.d/backup",
		"vacuum.sh | 30 2 * * 1-5 | /etc/cron.d/backup",
		"certbot | 0 */12 * * * | /etc/cron.d/certbot",
		"artisan schedule:run | * * * * * | user crontab",
		"curl | 0 3 * * * | user crontab",
		"mysqldump | 15 4 * * * | user crontab",
		"curl (2) | 0 5 1 * * | user crontab",
		"sync.sh | 0 1 * * sun | user crontab",
	}
	if strings.Join(got, "\n") != strings.Join(expect, "\n") {
		t.Fatalf("entries:\n%s", strings.Join(got, "\n"))
	}
	// cron hands the shell what comes before the first %; the rest is the command's input.
	if es[7].Command != "mysqldump -pwl-test-secret-0008 shop | gzip > /srv/dump-" {
		t.Fatalf("command up to %%: %q", es[7].Command)
	}

	// Nothing of a command, a user or an environment value leaves: the observations and the
	// tracker's jobs as they are sent.
	c := &Cron{Entries: func() []CronEntry { return es }, Loc: time.UTC}
	c.Exec(10, []string{"/bin/sh", "-c", es[2].Command}, at(1, 5))
	c.Exit(10, 1, 0, at(1, 6))
	obs := c.Observations(at(1, 7))
	tr := &Tracker{}
	tr.Update("cron", obs, at(1, 7))
	b1, _ := json.Marshal(obs)
	b2, _ := json.Marshal(tr.Jobs())
	for _, b := range [][]byte{b1, b2} {
		s := string(b)
		for _, leak := range []string{"wl-test-secret", "www-data", "postgres://", "db.internal", "/var/www", "ops@", "deploy"} {
			if strings.Contains(s, leak) {
				t.Fatalf("%q leaked: %s", leak, s)
			}
		}
	}
	if j := tr.Jobs()[0]; j.Name != "pg_dump" || j.State != Failed {
		t.Fatalf("worst first, the failed pg_dump: %+v", j)
	}
}

